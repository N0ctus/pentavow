import fs from 'fs';
import zlib from 'zlib';

function readPixels(p) {
  const buf = fs.readFileSync(p);
  let pos = 8, width, height, idatBuffers = [];
  while (pos < buf.length) {
    const len = buf.readUInt32BE(pos);
    const type = buf.toString('ascii', pos + 4, pos + 8);
    const data = buf.subarray(pos + 8, pos + 8 + len);
    if (type === 'IHDR') { width = data.readUInt32BE(0); height = data.readUInt32BE(4); }
    else if (type === 'IDAT') idatBuffers.push(data);
    pos += 12 + len;
  }
  const inflated = zlib.inflateSync(Buffer.concat(idatBuffers));
  const rowSize = width * 4 + 1;
  const pixels = Buffer.alloc(width * height * 4);
  for (let y = 0; y < height; y++) {
    const filter = inflated[y * rowSize];
    const rowOffset = y * rowSize + 1;
    for (let x = 0; x < width * 4; x++) {
      let val = inflated[rowOffset + x];
      const a = x >= 4 ? pixels[y * width * 4 + x - 4] : 0;
      const b = y > 0 ? pixels[(y - 1) * width * 4 + x] : 0;
      const c = (x >= 4 && y > 0) ? pixels[(y - 1) * width * 4 + x - 4] : 0;
      if (filter === 1) val = (val + a) & 0xff;
      else if (filter === 2) val = (val + b) & 0xff;
      else if (filter === 3) val = (val + Math.floor((a + b) / 2)) & 0xff;
      else if (filter === 4) {
        const p = a + b - c;
        const pa = Math.abs(p - a); const pb = Math.abs(p - b); const pc = Math.abs(p - c);
        let pr = (pa <= pb && pa <= pc) ? a : (pb <= pc ? b : c);
        val = (val + pr) & 0xff;
      }
      pixels[y * width * 4 + x] = val;
    }
  }
  return { width, height, pixels };
}

const grass = readPixels('public/map/pixel_grass_tile.png');
const water = readPixels('public/map/pixel_water_tile.png');

const grassB64 = grass.pixels.toString('base64');
const waterB64 = water.pixels.toString('base64');

const tsContent = `// Auto-generated byte data from public/map/pixel_grass_tile.png and pixel_water_tile.png
// 48x48 RGBA tile textures for infinite procedural canvas rendering

const base64ToUint8 = (b64: string): Uint8Array => {
  const binary = atob(b64);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) {
    bytes[i] = binary.charCodeAt(i);
  }
  return bytes;
};

const GRASS_B64 = "${grassB64}";
const WATER_B64 = "${waterB64}";

export const PMD_TILE_SIZE = 48;

let _grassData: Uint8Array | null = null;
let _waterData: Uint8Array | null = null;

export const getGrassBytes = (): Uint8Array => {
  if (!_grassData) _grassData = base64ToUint8(GRASS_B64);
  return _grassData;
};

export const getWaterBytes = (): Uint8Array => {
  if (!_waterData) _waterData = base64ToUint8(WATER_B64);
  return _waterData;
};

/**
 * Samples RGBA pixel from the 48x48 PMD grass tile at world coordinates (wx, wy).
 */
export const samplePmdGrass = (wx: number, wy: number): readonly [number, number, number] => {
  const bytes = getGrassBytes();
  const tx = ((wx % PMD_TILE_SIZE) + PMD_TILE_SIZE) % PMD_TILE_SIZE;
  const ty = ((wy % PMD_TILE_SIZE) + PMD_TILE_SIZE) % PMD_TILE_SIZE;
  const idx = (ty * PMD_TILE_SIZE + tx) * 4;
  return [bytes[idx], bytes[idx + 1], bytes[idx + 2]];
};

/**
 * Samples RGBA pixel from the 48x48 PMD wavy water tile at world coordinates (wx, wy).
 */
export const samplePmdWater = (wx: number, wy: number): readonly [number, number, number] => {
  const bytes = getWaterBytes();
  const tx = ((wx % PMD_TILE_SIZE) + PMD_TILE_SIZE) % PMD_TILE_SIZE;
  const ty = ((wy % PMD_TILE_SIZE) + PMD_TILE_SIZE) % PMD_TILE_SIZE;
  const idx = (ty * PMD_TILE_SIZE + tx) * 4;
  return [bytes[idx], bytes[idx + 1], bytes[idx + 2]];
};
`;

fs.writeFileSync('src/utils/worldGen/pmdTileData.ts', tsContent);
console.log('Successfully created src/utils/worldGen/pmdTileData.ts');
