console.log('--- Horizontal grid lines (rows) ---');
const yLines = [];
for (let y = 160; y < 765; y++) {
  // Check if pixel at (9, y), (15, y), (25, y) are grid border color or if there's a line
  // Let's check non-teal across x=8..758
  let nonTeal = 0;
  for (let x = 8; x <= 758; x++) {
    const [r, g, b] = getPixel(x, y);
    if (!(r === 0 && g === 128 && b === 128)) nonTeal++;
  }
  if (nonTeal > 740) {
    yLines.push(y);
  }
}
